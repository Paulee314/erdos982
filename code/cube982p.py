#!/usr/bin/env python3
"""Erdős #982 search, version p ("proof"): the cube982o.py search (compact lex-leader + distance-order extension) run in
BATCHES with one DIMACS file and one DRUP proof per batch, so that the whole search is a set of checkable UNSAT proofs.

Batch CNF  =  base clauses (F1, F2, exactly/at-most K, order axioms, geometric order clauses)
           +  for every piece i of the batch, with a fresh activation variable act_i:
                 the piece's unit literals as 2-literal clauses  (u ∨ ¬act_i)        (55 per piece at n = 12)
                 its compact lex-leader clauses                   (C ∨ ¬act_i)        (~1,200 per piece)
                 [below-K: its at-least-b cardinality clauses     (C ∨ ¬act_i)]
           +  one clause  (act_1 ∨ act_2 ∨ ... ∨ act_m)   "some piece of the batch is active".
The solver handles the pieces one by one with the single assumption act_i.  UNSAT under that assumption means the
clause (¬act_i) is RUP in the current clause database, so it is added as a clause (and CaDiCaL writes it to the proof,
where a checker verifies it by unit propagation).  When every piece is refuted the big OR clause is falsified by unit
propagation and a final solve() with no assumptions ends the proof with the empty clause.  A checker (drat-trim,
cake_lpr, or the small forward checker rupcheck.c in this folder) then certifies: the batch CNF is unsatisfiable, i.e.
no piece of the batch has a structure.  Each piece's CNF (base + its own clauses) is the sub-formula with act_i = 1,
act_j = 0 (j ≠ i), so this is exactly cube982o.py's statement for the batch.  A piece that IS satisfiable yields a
structure (written to the .sol file as cube982o.py does), is blocked clause by clause, and the batch proof simply
does not end with the empty clause for that batch (the batch is then marked SAT and the structures go to the algebra).
Usage: cube982p.py n K residue W batch_size outdir [first_batch] [n_batches]   (batches already in w<r>.done with final_unsat True are skipped; restart-safe)
Env:   BELOW=1 / ATMOST=1 as cube982o.py; NOWRITE=1 skips writing the CNF/proof files (timing only); NOCNF=1 writes the proof but not the CNF (the CNF is regenerated by the checker script)."""
import sys, os, time, datetime, resource
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from e982lib import Enc, partitions
from pysat.solvers import Cadical153
from pysat.card import CardEnc, EncType
def setup(n, K, BELOW, ATMOST):
    """the encoding and the piece list of a cover (deterministic: the checker rebuilds the same variable numbering)"""
    enc = Enc(n, K, order=True, atmost=BELOW or ATMOST)
    cubes = list(partitions(n - 1, K - 1, False)) if BELOW else list(partitions(n - 1, K, False)) if ATMOST else enc.cubes()
    return enc, cubes, enc.keep(cubes)
def batch_cnf(enc, cubes, batch, BELOW):
    """base clauses + every piece's clauses guarded by its activation literal + 'some piece is active'; returns (F, acts)"""
    F = list(enc.clauses); acts = {}
    for i in batch:
        a = enc.pool.id(('act', i)); acts[i] = a; rg = cubes[i]
        for cl in enc.unit_clauses(rg): F.append(cl + [-a])
        if not BELOW:
            for cl in enc.sym_compact(rg): F.append(cl + [-a])
        else:
            b = max(rg) + 1
            if b >= 2:
                for c in enc.V:
                    if c == 0: continue
                    for cl in CardEnc.atleast(lits=enc.REPS[c], bound=b, vpool=enc.pool, encoding=EncType.seqcounter).clauses: F.append(cl + [-a])
    F.append([acts[i] for i in batch])
    return F, acts
def write_cnf(path, F, nv):
    with open(path, 'w') as f:
        f.write(f'p cnf {nv} {len(F)}\n'); f.write('\n'.join(' '.join(map(str, cl)) + ' 0' for cl in F) + '\n')
def main():
    n = int(sys.argv[1]); K = int(sys.argv[2]); RES = int(sys.argv[3]); W_N = int(sys.argv[4]); BS = int(sys.argv[5]); OUT = sys.argv[6]
    FIRST = int(sys.argv[7]) if len(sys.argv) > 7 else 0; NB = int(sys.argv[8]) if len(sys.argv) > 8 else 10**9
    BELOW = os.environ.get('BELOW') == '1'; ATMOST = os.environ.get('ATMOST') == '1'; NOWRITE = os.environ.get('NOWRITE') == '1'; NOCNF = os.environ.get('NOCNF') == '1'
    enc, cubes, keep = setup(n, K, BELOW, ATMOST)
    mine = [i for i in range(len(cubes)) if i % W_N == RES and keep[i]]
    batches = [mine[b:b + BS] for b in range(0, len(mine), BS)]
    os.makedirs(OUT, exist_ok=True)
    tag = 'below' if BELOW else 'atmost' if ATMOST else 'exact'
    done_path = os.path.join(OUT, f'w{RES}.done'); done = set()
    if os.path.exists(done_path):
        for l in open(done_path):
            w = l.split()
            if w and w[0] == 'batch' and 'final_unsat True' in l: done.add(int(w[1]))
    print(f"n={n} K={K} {tag}: {len(enc.clauses)} base clauses, {enc.pool.top} base variables; worker {RES}/{W_N}: {len(mine)} pieces, batches of {BS}: {len(batches)} batches, {len(done)} already done", flush=True)
    for bi, batch in enumerate(batches):
        t0 = time.time(); c0 = time.process_time()
        F, acts = batch_cnf(enc, cubes, batch, BELOW)      # always built, so that the variable numbering is a function of (cover, residue, W, batch size, batch) only
        if bi < FIRST or bi >= FIRST + NB or bi in done: continue
        nv = enc.pool.top
        s = Cadical153(bootstrap_with=F, with_proof=True)
        nsol = 0; sols = []
        for i in batch:
            a = acts[i]
            while s.solve(assumptions=[a]):
                m = set(x for x in s.get_model() if x > 0); sols.append((i, enc.structure(m))); nsol += 1
                s.add_clause(enc.block_clause(m) + [-a])
            s.add_clause([-a])                 # RUP: act_i alone propagates to a conflict
        final_unsat = not s.solve()
        proof = s.get_proof() if not NOWRITE else None
        s.delete()
        cpu = time.process_time() - c0; hwm = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss // (1024 * 1024 if sys.platform == 'darwin' else 1024)
        name = f'{tag}_w{RES}_b{bi}'
        plen = 0
        if not NOWRITE:
            if not NOCNF:
                write_cnf(os.path.join(OUT, name + '.cnf'), F, nv)
            with open(os.path.join(OUT, name + '.drup'), 'w') as f:
                f.write('\n'.join(proof) + '\n')
            plen = len(proof)
            if sols:
                with open(os.path.join(OUT, name + '.sol'), 'w') as f:
                    for i, st in sols: f.write(f'{i} {st}\n')
        with open(os.path.join(OUT, f'w{RES}.done'), 'a') as f:
            f.write(f"batch {bi} pieces {batch[0]}..{batch[-1]} ({len(batch)}) structures {nsol} final_unsat {final_unsat} clauses {len(F)} vars {nv} proof_lines {plen} wall {time.time()-t0:.2f} cpu={cpu:.2f} hwmMB {hwm} {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}\n")
        print(f"batch {bi}: {len(batch)} pieces, {nsol} structures, final UNSAT={final_unsat}, {len(F)} clauses, proof {plen} lines, cpu {cpu:.1f}s wall {time.time()-t0:.1f}s, peak RSS {hwm} MB", flush=True)

if __name__ == '__main__': main()
